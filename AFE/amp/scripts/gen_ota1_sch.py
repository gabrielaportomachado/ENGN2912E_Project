#!/usr/bin/env python3
"""Generate xschem/ota1.sch and xschem/ota1.sym (stage-1 OTA, A3).  Connectivity is by net labels (lab_pin), so it does
not depend on wire geometry.  The .sch is the source of truth once generated; rerun this only to regenerate it.
Sizes are the .param names of spice/ota1_params.spice (single quotes: ngspice evaluates them)."""
import os
HERE = os.path.dirname(os.path.abspath(__file__)); X = os.path.join(HERE, '..', 'xschem')
n = [0]
def nm(p='p'):
    n[0] += 1; return f'{p}{n[0]}'
out = ['v {xschem version=3.4.7 file_version=1.2}', 'G {}', 'K {}', 'V {}', 'S {}', 'E {}']
def pin(x, y, lab, side):
    rot, flip = {'L': (0, 0), 'R': (0, 1), 'T': (3, 0), 'B': (1, 0)}[side]
    out.append(f'C {{lab_pin.sym}} {x} {y} {rot} {flip} {{name={nm()} sig_type=std_logic lab={lab}}}')
def mos(kind, name, x, y, W, L, M, d, g, s, b):
    sym = 'pfet_03v3' if kind == 'p' else 'nfet_03v3'
    attr = (f"name={name}\nL='{L}'\nW='{W}'\nnf=1\nm='{M}'\n"
            f"ad='DIFF*{W}*0.18u'\nas='DIFF*{W}*0.18u'\npd='DIFF*2*({W}+0.18u)'\nps='DIFF*2*({W}+0.18u)'\nnrd=0\nnrs=0\nsa=0 sb=0 sd=0\nmodel={sym}\nspiceprefix=X")
    out.append(f'C {{symbols/{sym}.sym}} {x} {y} 0 0 {{{attr}}}')
    # pin positions (rot 0): pfet D(+20,+30) S(+20,-30); nfet D(+20,-30) S(+20,+30); G(-20,0); B(+20,0)
    top, bot = ((s, d) if kind == 'p' else (d, s))
    pin(x + 20, y - 30, top, 'R'); pin(x + 20, y + 30, bot, 'R'); pin(x - 20, y, g, 'L'); pin(x + 20, y, b, 'R')
# --- devices (names -> Xmb, Xmt, Xm1... in the netlist)
mos('p', 'mb', -420, -260, 'OTA_WT', 'OTA_LT', 'OTA_KB', 'ibias', 'ibias', 'vdd', 'vdd')
mos('p', 'mt', -250, -260, 'OTA_WT', 'OTA_LT', 'OTA_KT', 'tail', 'ibias', 'vdd', 'vdd')
mos('p', 'm1', -330, -90, 'OTA_WP', 'OTA_LP', 'OTA_KP', 'd1', 'inn', 'tail', 'vdd')
mos('p', 'm2', -150, -90, 'OTA_WP', 'OTA_LP', 'OTA_KP', 'o1', 'inp', 'tail', 'vdd')
mos('n', 'm3', -330, 60, 'OTA_WN', 'OTA_LN', 'OTA_KN', 'd1', 'd1', 'vss', 'vss')
mos('n', 'm4', -150, 60, 'OTA_WN', 'OTA_LN', 'OTA_KN', 'o1', 'd1', 'vss', 'vss')
mos('p', 'm7', 160, -90, 'OTA_WT', 'OTA_LT', 'OTA_K7', 'out', 'ibias', 'vdd', 'vdd')
mos('n', 'm6', 160, 60, 'OTA_WN', 'OTA_LN', 'OTA_K6', 'out', 'o1', 'vss', 'vss')
# Miller capacitor (MIM), G (top) = o1, B (bottom) = out
out.append("C {symbols/cap_mim_2f0fF.sym} 30 -20 0 0 {name=cc\nW='OTA_LCC'\nL='OTA_LCC'\nmodel=cap_mim_2f0_m2m3_noshield\nspiceprefix=X\nm=1}")
pin(30, -50, 'o1', 'T'); pin(30, 10, 'out', 'B')
# --- interface pins (order = order of the .subckt line: inp inn out vdd vss ibias)
for i, (k, lab) in enumerate([('ipin', 'inp'), ('ipin', 'inn'), ('opin', 'out'), ('iopin', 'vdd'), ('iopin', 'vss'), ('ipin', 'ibias')]):
    out.append(f'C {{{k}.sym}} {-560 if k != "opin" else 330} {-300 + 40 * i} 0 {1 if k == "opin" else 0} {{name={nm("io")} lab={lab}}}')
out.append("T {A3 stage-1 OTA: PMOS-input two-stage Miller (generated by scripts/gen_ota1_sch.py). Sizes = spice/ota1_params.spice.} -560 -360 0 0 0.3 0.3 {}")
open(os.path.join(X, 'ota1.sch'), 'w').write('\n'.join(out) + '\n')
# --- symbol: pin order must match the .subckt line
pins = [('inp', 'in', -1), ('inn', 'in', -1), ('ibias', 'in', -1), ('out', 'out', 1), ('vdd', 'inout', 0), ('vss', 'inout', 0)]
s = ['v {xschem version=3.4.7 file_version=1.2}', 'G {}',
     'K {type=subcircuit\nformat="@name @pinlist @symname"\ntemplate="name=x1"\n}', 'V {}', 'S {}', 'E {}',
     'L 4 -60 -80 60 -80 {}', 'L 4 60 -80 60 80 {}', 'L 4 60 80 -60 80 {}', 'L 4 -60 80 -60 -80 {}']
lines = {'inp': -30, 'inn': 0, 'ibias': 30}
for lab, d, side in pins:
    if side == -1:
        y = lines[lab]; s += [f'L 4 -80 {y} -60 {y} {{}}', f'B 5 -82.5 {y-2.5} -77.5 {y+2.5} {{name={lab} dir={d}}}', f'T {{{lab}}} -55 {y-4} 0 0 0.2 0.2 {{}}']
    elif side == 1:
        s += ['L 4 60 0 80 0 {}', f'B 5 77.5 -2.5 82.5 2.5 {{name={lab} dir={d}}}', f'T {{{lab}}} 55 -4 0 1 0.2 0.2 {{}}']
    else:
        y = -100 if lab == 'vdd' else 100; y0 = -80 if lab == 'vdd' else 80
        s += [f'L 4 0 {y0} 0 {y} {{}}', f'B 5 -2.5 {y-2.5} 2.5 {y+2.5} {{name={lab} dir={d}}}', f'T {{{lab}}} 5 {y0 + (12 if lab=="vdd" else -22)} 0 0 0.2 0.2 {{}}']
s += ['T {ota1} 0 -8 0 0 0.3 0.3 {}', 'T {@name} 62 -100 0 0 0.25 0.25 {}']
open(os.path.join(X, 'ota1.sym'), 'w').write('\n'.join(s) + '\n')
print('wrote xschem/ota1.sch and xschem/ota1.sym')
