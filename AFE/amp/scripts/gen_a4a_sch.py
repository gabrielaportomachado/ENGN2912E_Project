#!/usr/bin/env python3
"""A4a: writes xschem/ota2.{sch,sym} and xschem/bias_gen.{sch,sym}.  Connectivity by net labels (lab_pin), so geometry only has to avoid overlaps.  Pin order of the
.subckt line is xschem's own (inputs, outputs, inouts), and spice/ota2.spice / spice/bias_gen.spice use the same order.  The tables below are typed
independently of the hand netlists (the equivalence run, scripts/equiv_xschem_a4a.sh, compares them)."""
import os
HERE = os.path.dirname(os.path.abspath(__file__)); X = os.path.join(HERE, '..', 'xschem')
class Sch:
    def __init__(self): self.n = 0; self.out = ['v {xschem version=3.4.7 file_version=1.2}', 'G {}', 'K {}', 'V {}', 'S {}', 'E {}']
    def nm(self, p='p'): self.n += 1; return f'{p}{self.n}'
    def pin(self, x, y, lab, side):
        rot, flip = {'L': (0, 0), 'R': (0, 1), 'T': (3, 0), 'B': (1, 0)}[side]
        self.out.append(f'C {{lab_pin.sym}} {x} {y} {rot} {flip} {{name={self.nm()} sig_type=std_logic lab={lab}}}')
    def mos(self, kind, name, x, y, W, L, M, d, g, s, b):
        sym = 'pfet_03v3' if kind == 'p' else 'nfet_03v3'
        attr = (f"name={name}\nL='{L}'\nW='{W}'\nnf=1\nm='{M}'\nad='DIFF*{W}*0.18u'\nas='DIFF*{W}*0.18u'\npd='DIFF*2*({W}+0.18u)'\nps='DIFF*2*({W}+0.18u)'\n"
                f"nrd=0\nnrs=0\nsa=0 sb=0 sd=0\nmodel={sym}\nspiceprefix=X")
        self.out.append(f'C {{symbols/{sym}.sym}} {x} {y} 0 0 {{{attr}}}')
        top, bot = ((s, d) if kind == 'p' else (d, s))
        self.pin(x + 20, y - 30, top, 'R'); self.pin(x + 20, y + 30, bot, 'R'); self.pin(x - 20, y, g, 'L'); self.pin(x + 20, y, b, 'R')
    def res(self, name, model, x, y, W, L, p, m, b):
        self.out.append(f"C {{symbols/{model}.sym}} {x} {y} 0 0 {{name={name}\nW='{W}'\nL='{L}'\nmodel={model}\nspiceprefix=X\nm=1}}")
        self.pin(x, y - 30, p, 'T'); self.pin(x, y + 30, m, 'B'); self.pin(x - 20, y, b, 'L')
    def cap(self, name, x, y, W, top, bot):
        self.out.append(f"C {{symbols/cap_mim_2f0fF.sym}} {x} {y} 0 0 {{name={name}\nW='{W}'\nL='{W}'\nmodel=cap_mim_2f0_m2m3_noshield\nspiceprefix=X\nm=1}}")
        self.pin(x, y - 30, top, 'T'); self.pin(x, y + 30, bot, 'B')
    def ports(self, items, x0=-700, y0=-300):
        for i, (k, lab) in enumerate(items):
            self.out.append(f'C {{{k}.sym}} {x0 if k != "opin" else 700} {y0 + 40 * i} 0 {1 if k == "opin" else 0} {{name={self.nm("io")} lab={lab}}}')
    def text(self, t): self.out.append(f'T {{{t}}} -700 -360 0 0 0.3 0.3 {{}}')
    def write(self, name): open(os.path.join(X, name + '.sch'), 'w').write('\n'.join(self.out) + '\n')
def sym(name, ins, outs, inouts):
    """pin order of the symbol = xschem netlist order: inputs, outputs, inouts"""
    s = ['v {xschem version=3.4.7 file_version=1.2}', 'G {}', f'K {{type=subcircuit\nformat="@name @pinlist @symname"\ntemplate="name=x1"\n}}', 'V {}', 'S {}', 'E {}']
    h = 20 * max(len(ins), len(outs), 2) + 20
    s += [f'L 4 -60 {-h} 60 {-h} {{}}', f'L 4 60 {-h} 60 {h} {{}}', f'L 4 60 {h} -60 {h} {{}}', f'L 4 -60 {h} -60 {-h} {{}}']
    for i, lab in enumerate(ins):
        y = -h + 40 + 40 * i
        s += [f'L 4 -80 {y} -60 {y} {{}}', f'B 5 -82.5 {y-2.5} -77.5 {y+2.5} {{name={lab} dir=in}}', f'T {{{lab}}} -55 {y-4} 0 0 0.2 0.2 {{}}']
    for i, lab in enumerate(outs):
        y = -h + 40 + 40 * i
        s += [f'L 4 60 {y} 80 {y} {{}}', f'B 5 77.5 {y-2.5} 82.5 {y+2.5} {{name={lab} dir=out}}', f'T {{{lab}}} 55 {y-4} 0 1 0.2 0.2 {{}}']
    for i, lab in enumerate(inouts):
        xx = -20 + 40 * i
        yy, y0 = (-h - 20, -h) if lab == 'vdd' else (h + 20, h)
        s += [f'L 4 {xx} {y0} {xx} {yy} {{}}', f'B 5 {xx-2.5} {yy-2.5} {xx+2.5} {yy+2.5} {{name={lab} dir=inout}}']
    s += [f'T {{{name}}} 0 -8 0 0 0.3 0.3 {{}}', 'T {@name} 62 -100 0 0 0.25 0.25 {}']
    open(os.path.join(X, name + '.sym'), 'w').write('\n'.join(s) + '\n')
# ---------------- ota2: pins inp inn vbn | out | vdd vss
a = Sch()
a.mos('n', 'mt', -300, 120, 'OTA2_WT', 'OTA2_LT', '1', 'tail', 'vbn', 'vss', 'vss')
a.mos('n', 'm1', -380, -20, 'OTA2_WP', 'OTA2_LP', '1', 'd1', 'inp', 'tail', 'vss')
a.mos('n', 'm2', -220, -20, 'OTA2_WP', 'OTA2_LP', '1', 'o2', 'inn', 'tail', 'vss')
a.mos('p', 'm3', -380, -170, 'OTA2_WL', 'OTA2_LL', '1', 'd1', 'd1', 'vdd', 'vdd')
a.mos('p', 'm4', -220, -170, 'OTA2_WL', 'OTA2_LL', '1', 'o2', 'd1', 'vdd', 'vdd')
a.mos('n', 'mf', 40, -60, 'OTA2_WF', 'OTA2_LF', '1', 'vdd', 'o2', 'out', 'vss')
a.mos('n', 'ms', 40, 100, '16u', '4u', 'BM_KSF', 'out', 'vbn', 'vss', 'vss')
a.cap('cc', -80, 40, 'LCC2', 'o2', 'vss')
a.ports([('ipin', 'inp'), ('ipin', 'inn'), ('ipin', 'vbn'), ('opin', 'out'), ('iopin', 'vdd'), ('iopin', 'vss')])
a.text('A4a stage-2 OTA: NMOS pair + PMOS mirror load + NMOS follower (generated by scripts/gen_a4a_sch.py). Sizes = spice/afe_params.spice.')
a.write('ota2'); sym('ota2', ['inp', 'inn', 'vbn'], ['out'], ['vdd', 'vss'])
# ---------------- bias_gen: pins (outputs) vbn vcm_in vg1 vcm_out vg2 | vdd vss
b = Sch()
b.mos('p', 'mp2', -600, -200, '40u', '4u', '1', 'a', 'a', 'vdd', 'vdd')
b.mos('p', 'mp1', -420, -200, '40u', '4u', '1', 'vbn', 'a', 'vdd', 'vdd')
b.mos('n', 'mn1', -420, -20, '16u', '4u', '1', 'vbn', 'vbn', 'vss', 'vss')
b.mos('n', 'mn2', -600, -20, '16u', '4u', '4', 'a', 'vbn', 'r1', 'vss')
b.res('rb', 'ppolyf_u_1k', -600, 140, '2u', 'RB_L', 'r1', '', 'vss')
b.pin(-600, 170, 'vss', 'B')
b.mos('p', 's1', -240, -200, '0.5u', '4u', '1', 's1', 's1', 'vdd', 'vdd')
b.mos('p', 's2', -240, -100, '0.5u', '4u', '1', 's2', 's2', 's1', 'vdd')
b.mos('p', 's3', -240, 0, '0.5u', '4u', '1', 'vbn', 'vbn', 's2', 'vdd')
for i, (nm, p, m, L) in enumerate([('ra1', 'vdd', 'vg1', '(VDDN-VCM_IN-VTT)/ILAD/3000*1u'), ('ra2', 'vg1', 'vcm_in', 'VTT/ILAD/3000*1u'), ('ra3', 'vcm_in', 'vss', 'VCM_IN/ILAD/3000*1u'),
                                   ('rb1', 'vdd', 'vg2', '(VDDN-VOCM-VTT)/ILAD/3000*1u'), ('rb2', 'vg2', 'vcm_out', 'VTT/ILAD/3000*1u'), ('rb3', 'vcm_out', 'vss', 'VOCM/ILAD/3000*1u')]):
    b.res(nm, 'ppolyf_u_3k', 0 + 120 * i, 100, '1u', L, p, m, 'vss')
b.ports([('opin', 'vbn'), ('opin', 'vcm_in'), ('opin', 'vg1'), ('opin', 'vcm_out'), ('opin', 'vg2'), ('iopin', 'vdd'), ('iopin', 'vss')])
b.text('A4a real bias: beta-multiplier master + start-up stack + two resistor ladders (generated by scripts/gen_a4a_sch.py).')
b.write('bias_gen'); sym('bias_gen', [], ['vbn', 'vcm_in', 'vg1', 'vcm_out', 'vg2'], ['vdd', 'vss'])
print('wrote xschem/ota2.{sch,sym}, bias_gen.{sch,sym}')
