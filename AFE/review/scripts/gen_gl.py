#!/usr/bin/env python3
"""AUDIT step 4: delay-annotated copy of the HARDENED netlist for Icarus (Icarus cannot annotate this SDF: `$sdf_annotate` aborts with
"NULL handle passed to vpi_scan" on the PDK flop models, with and without -ginterconnect; tried twice, 2026-11-20).
Input : AFE/adc/lg/runs/d3/final/nl/adc8_top.nl.v (not edited) + final/sdf/nom_<corner>/adc8_top__nom_<corner>.sdf (OpenSTA, nom SPEF).
Output: the same netlist text where every cell output pin drives a private wire and `assign #(rise, fall) <net> = <wire>;` carries the WORST IOPATH arc of that
        output from the SDF (max over the input pins and conditions).  Cells are then compiled with -DFUNCTIONAL (PDK models without specify blocks).
Not modelled: INTERCONNECT delays (<= 0.09 ns on SCLK, RSTN; listed in the header comment of the output), per-input-pin arcs, the RN -> Q arc (0 in this SDF),
setup / hold checks.   usage: gen_gl.py <corner e.g. tt_025C_3v30> <out.v>
LP (2026-11-20): gen_gl.py <corner> <out.v> <LibreLane final dir> <top module>  does the same for another hardened netlist (the macro afe_dig: AFE/dig); without the two extra
arguments nothing changes."""
import re, sys, os
HERE = os.path.dirname(os.path.abspath(__file__))
RUN = os.path.normpath(os.path.join(HERE, '..', '..', 'adc', 'lg', 'runs', 'd3', 'final'))
OUTP = ('Z', 'ZN', 'Q', 'QN')


def parse_sdf(path):
    d = {}
    cur = None
    icmax = 0.0
    for line in open(path):
        m = re.search(r'\(INSTANCE\s*([^)]*)\)', line)
        if m:
            cur = m.group(1).strip().replace('\\', '')
            continue
        m = re.search(r'\(INTERCONNECT\s+\S+\s+\S+\s+\(([^)]*)\)', line)
        if m and m.group(1):
            icmax = max(icmax, float(m.group(1).split(':')[-1]))
        m = re.search(r'\(IOPATH\s+(?:\((?:posedge|negedge)\s+\S+\)|\S+)\s+(\S+)\s+\(([^)]*)\)\s+\(([^)]*)\)', line)
        if m and cur:
            o = m.group(1)
            e = d.setdefault(cur, {}).setdefault(o, [0.0, 0.0, 1e9, 1e9])
            for i, v in enumerate((m.group(2), m.group(3))):
                if v.strip():
                    x = float(v.split(':')[-1])
                    e[i] = max(e[i], x)
                    if x > 0:
                        e[2 + i] = min(e[2 + i], x)
    return d, icmax


def main(corner, out, run=RUN, top='adc8_top'):
    sdf, icmax = parse_sdf(os.path.join(run, 'sdf', 'nom_' + corner, '%s__nom_%s.sdf' % (top, corner)))
    txt = open(os.path.join(run, 'nl', '%s.nl.v' % top)).read()
    wires = []
    assigns = []
    stats = dict(inst=0, outs=0, nodelay=0)

    def repl(m):
        typ, name, body = m.group(1), m.group(2), m.group(3)
        key = name.strip().lstrip('\\')
        stats['inst'] += 1

        def pin(pm):
            p, net = pm.group(1), pm.group(2)
            if p not in OUTP or not net.strip():
                return pm.group(0)
            w = 'gl_w%d' % len(wires)
            wires.append(w)
            r, f, _, _ = sdf.get(key, {}).get(p, [0.0, 0.0, 0, 0])
            if key not in sdf or p not in sdf[key]:
                stats['nodelay'] += 1
            r = r if r > 0 else f
            f = f if f > 0 else r
            stats['outs'] += 1
            assigns.append(' assign #(%.3f, %.3f) %s = %s;' % (r, f, net, w))
            return '.%s(%s)' % (p, w)
        body2 = re.sub(r'\.(\w+)\(([^)]*)\)', pin, body)
        return ' %s %s (%s);' % (typ, name, body2)
    new = re.sub(r'^ (gf180mcu_fd_sc_mcu7t5v0__\w+) (\\\S+ |\w+) \((.*?)\);', repl, txt, flags=re.S | re.M)
    i = new.index(' gf180mcu_fd_sc_mcu7t5v0__')
    src = 'AFE/adc/lg/runs/d3/final/nl/adc8_top.nl.v' if (run == RUN and top == 'adc8_top') else os.path.join(run, 'nl', '%s.nl.v' % top)
    hdr = ('`timescale 1ns/1ps\n// AUDIT: delay-annotated copy of %s, corner %s, generated by AFE/review/scripts/gen_gl.py.\n'
           '// %d cell instances, %d outputs with `assign #(rise, fall)` from the worst SDF IOPATH arc (%d outputs had no SDF entry: delay 0).  INTERCONNECT delays not modelled (largest in the SDF: %.3f ns).\n'
           % (src, corner, stats['inst'], stats['outs'], stats['nodelay'], icmax))
    new = hdr + new[:i] + ''.join(' wire %s;\n' % w for w in wires) + new[i:]
    j = new.rindex('endmodule')
    new = new[:j] + '\n'.join(assigns) + '\n' + new[j:]
    open(out, 'w').write(new)
    print('gen_gl %s: %d instances, %d annotated outputs, %d without SDF entry, max interconnect %.3f ns -> %s' % (corner, stats['inst'], stats['outs'], stats['nodelay'], icmax, out))


if __name__ == '__main__':
    if len(sys.argv) >= 5:
        main(sys.argv[1], sys.argv[2], os.path.abspath(sys.argv[3]), sys.argv[4])
    else:
        main(sys.argv[1], sys.argv[2])
