#!/usr/bin/env python3
"""Writes AFE/review/tb/stubs_audit.v = the audit copy of AFE/top/stubs_analog.v (the original is not edited).  F1 (2026-11-20): the copy was made by an unsaved script during the audit; this
script reproduces it byte for byte from the stubs of commit be40b54 and keeps the copy in step with the original when its pins change.
The four differences: (0) header + `include "audit_delays.vh"; (1) the OR2 stub is compiled only without GLS (with GLS the PDK cell model is used); (2) the comparator stub takes its decision and
reset delays from audit_delays.vh (TDEC, TCRST) and decides only if the clock is still high; (3) nothing else (the one-shot keeps its parameter T_FS).
usage: python3 gen_stubs_audit.py [in.v] [out.v]"""
import os, sys
R = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(R, '..', 'top', 'stubs_analog.v')
dst = sys.argv[2] if len(sys.argv) > 2 else os.path.join(R, 'tb', 'stubs_audit.v')
t = open(src).read()
HEAD = ('// AUDIT COPY of AFE/top/stubs_analog.v (generated by a script from the original; the original is not edited).  Differences: (1) the OR2 stub is compiled only without GLS\n'
        '// (with GLS the PDK cell model is used); (2) the comparator stub takes its decision / reset delays from audit_delays.vh (TDEC, TCRST) instead of the fixed 1.5 / 0.6 ns;\n'
        '// (3) the one-shot stub pulse width is the parameter T_FS as before (3.56 ms typ).\n'
        '`include "audit_delays.vh"\n')
REPL = [
    ('`timescale 1ns/1ps\n', '`timescale 1ns/1ps\n' + HEAD),
    ('module gf180mcu_fd_sc_mcu7t5v0__or2_1 (A1, A2, Z); input A1, A2; output Z; assign #0.2 Z = A1 | A2; endmodule   // ESTIMATE delay',
     '`ifndef GLS\nmodule gf180mcu_fd_sc_mcu7t5v0__or2_1 (A1, A2, Z); input A1, A2; output Z; assign #0.2 Z = A1 | A2; endmodule\n`endif   // ESTIMATE delay'),
    ('    always @(posedge clk) begin #1.5 outp = (sim_vs >= sim_dacv); outn = ~outp; end',
     '    always @(posedge clk) begin #(`TDEC) if (clk) begin outp = (sim_vs >= sim_dacv); outn = ~outp; end end   // decision only if the clock is still high (window >= TDEC)'),
    ("    always @(negedge clk) begin #0.6 outp = 1'b1; outn = 1'b0; end", "    always @(negedge clk) begin #(`TCRST) outp = 1'b1; outn = 1'b0; end"),
]
for a, b in REPL:
    if t.count(a) != 1:
        sys.exit('gen_stubs_audit: pattern not found exactly once: %r' % a[:60])
    t = t.replace(a, b)
open(dst, 'w').write(t)
print('wrote', os.path.relpath(dst, os.path.join(R, '..', '..')))
