#!/usr/bin/env python3
"""top_frame.py (tapeout-todos): the organizer's block frame of dbs_afe_top, derived from floorplan.json.

    python3 AFE/layout/scripts/top_frame.py            writes AFE/layout/top_frame.json
    python3 AFE/layout/scripts/top_frame.py --check    exit 1 if top_frame.json is not what this script would write

Why: the organizer's block is 605 um tall and 1405 .. 1620 um wide, with pins 1-6 on the left edge and 7-20 on the top edge.
The L3a layout (floorplan.json, 605 x 1110 um, "core frame") is kept unchanged and rotated 90 degrees clockwise:
    core (x, y)  ->  top (y, CORE_W - x)          core west -> top edge, core south -> left edge, core north -> right, core east -> bottom
The outline is widened east to TOP_W (the extension holds the re-routed wires only).  Pads that land on the right or bottom edge
(E / REC / IPG of channels 0-1 on the core north edge, REF on the core east edge) are re-routed on Metal5 through the extension to the top edge:
a horizontal wire from the old pin position east to a riser column x_v, then up to the top edge.  Lower wires turn further east, so no two wires cross.
floorplan.json stays the source of the core geometry (floorplan.py check, mk_top.py, check_top.py all work in the core frame).
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
LAY = os.path.normpath(os.path.join(HERE, '..'))
OUT = os.path.join(LAY, 'top_frame.json')

TOP_W = 1405.0          # organizer range 1405 .. 1620 um; the smallest width keeps the extension (empty except the 7 wires) small
RISER_X0 = 1140.0       # first riser column (30 um east of the core edge)
RISER_PITCH = 20.0      # 2 um Metal5 wires on a 20 um pitch (18 um gap: coupling between the high-impedance E / REC wires stays small)
REF_RISER_GAP = 40.0    # REF riser 40 um east of the last channel riser
REF_TAP_COREY = 1080.0  # REF Metal3 vertical (core x 604.25) tapped here, inside the north bias corridor


def build():
    fp = json.load(open(os.path.join(LAY, 'floorplan.json')))
    cw, ch = float(fp['outline'][2]), float(fp['outline'][3])

    def rot(x, y):
        return (round(y, 3), round(cw - x, 3))

    pins, moved = [], []
    for q in fp['pins']:
        x, y = rot(q['x'], q['y'])
        side = {'W': 'N', 'S': 'W', 'N': 'E', 'E': 'S'}[q['side']]
        p = dict(name=q['name'], pad=q['pad'], side=side, x=x, y=y, layer=q['layer'], w=q['w'], core_side=q['side'])
        if side in ('E', 'S'):
            moved.append(p)
        pins.append(p)
    # channel wires first, highest y first (turns westmost), then REF
    chw = sorted([p for p in moved if p['side'] == 'E'], key=lambda p: -p['y'])
    ref = [p for p in moved if p['side'] == 'S']
    assert len(chw) == 6 and len(ref) == 1, (len(chw), len(ref))
    reroute = []
    for i, p in enumerate(chw):
        xv = RISER_X0 + RISER_PITCH * i
        reroute.append(dict(name=p['name'], from_xy=[ch, p['y']], riser_x=xv, wire_y=p['y']))
        p.update(side='N', x=xv, y=ch * 0 + cw, rerouted=True)
    xv_ref = RISER_X0 + RISER_PITCH * (len(chw) - 1) + REF_RISER_GAP
    ref_y = round(cw - 603.6, 3)                       # core x 602.6 .. 604.6 (Metal5 over the 3-5 stack at core x 604.25) -> top y 0.4 .. 2.4
    reroute.append(dict(name='REF', from_xy=[REF_TAP_COREY, ref_y], riser_x=xv_ref, wire_y=ref_y, core_tap=[604.25, REF_TAP_COREY]))
    ref[0].update(side='N', x=xv_ref, y=cw, rerouted=True)
    assert xv_ref + 1.0 < TOP_W
    # pad numbering: 1.. up the left edge (south to north), then the top edge west to east
    order = sorted([p for p in pins if p['side'] == 'W'], key=lambda p: p['y']) + sorted([p for p in pins if p['side'] == 'N'], key=lambda p: p['x'])
    pads = []
    for p in order:
        if p['pad'] not in [d['pad'] for d in pads]:
            pads.append(dict(n=len(pads) + 1, pad=p['pad'], side=p['side']))
    return {
        '_about': 'GENERATED by AFE/layout/scripts/top_frame.py from floorplan.json; do not edit by hand. Organizer block frame: the core (floorplan.json, '
                  '%g x %g um) rotated 90 deg clockwise, top (x, y) = (core_y, %g - core_x), outline widened east to %g um. Pads: 1-6 left edge, 7-20 top edge.' % (cw, ch, cw, TOP_W),
        'core_outline': fp['outline'],
        'core_trans': {'kl_dtrans': 'R270', 'disp': [0.0, cw], 'maps': '(x, y) -> (y, %g - x)' % cw},
        'outline': [0.0, 0.0, TOP_W, cw],
        'pins': pins,
        'reroute': reroute,
        'pads': pads,
    }


def main():
    d = build()
    txt = json.dumps(d, indent=1) + '\n'
    if '--check' in sys.argv:
        same = os.path.exists(OUT) and open(OUT).read() == txt
        print('top_frame.json', 'up to date' if same else 'DIFFERS from top_frame.py build: run python3 AFE/layout/scripts/top_frame.py')
        return 0 if same else 1
    open(OUT, 'w').write(txt)
    print('wrote %s: outline %g x %g um, %d pin bits, %d re-routed wires, pads %s' % (
        os.path.relpath(OUT), d['outline'][2], d['outline'][3], len(d['pins']), len(d['reroute']),
        ', '.join('%d %s (%s)' % (p['n'], p['pad'], p['side']) for p in d['pads'])))
    return 0


if __name__ == '__main__':
    sys.exit(main())
