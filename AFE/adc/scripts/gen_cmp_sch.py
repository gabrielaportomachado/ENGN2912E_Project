#!/usr/bin/env python3
"""D1: writes xschem/cmp_p.{sch,sym} (cell cmp_p) and xschem/cmp_inv.{sch,sym}.  Connectivity by net labels (lab_pin).  The device table below is typed independently of spice/comparator.spice
(the equivalence run, scripts/equiv_xschem_d1.sh, compares them).  cmp_n (the NMOS-input dual) is a spice-only contrast variant and is NOT drawn."""
import os
HERE = os.path.dirname(os.path.abspath(__file__)); X = os.path.join(HERE, '..', 'xschem')
class Sch:
    def __init__(self): self.n = 0; self.out = ['v {xschem version=3.4.7 file_version=1.2}', 'G {}', 'K {}', 'V {}', 'S {}', 'E {}']
    def nm(self, p='p'): self.n += 1; return f'{p}{self.n}'
    def pin(self, x, y, lab, side):
        rot, flip = {'L': (0, 0), 'R': (0, 1), 'T': (3, 0), 'B': (1, 0)}[side]
        self.out.append(f'C {{lab_pin.sym}} {x} {y} {rot} {flip} {{name={self.nm()} sig_type=std_logic lab={lab}}}')
    def mos(self, kind, name, x, y, W, L, d, g, s, b):
        sym = {'p': 'pfet_03v3', 'n': 'nfet_03v3'}[kind]
        attr = (f"name={name}\nL='{L}'\nW='{W}'\nnf=1\nm=1\nad='{W}*0.18u'\nas='{W}*0.18u'\npd='2*({W}+0.18u)'\nps='2*({W}+0.18u)'\n"
                f"nrd=0\nnrs=0\nsa=0 sb=0 sd=0\nmodel={sym}\nspiceprefix=X")
        self.out.append(f'C {{symbols/{sym}.sym}} {x} {y} 0 0 {{{attr}}}')
        top, bot = ((s, d) if kind == 'p' else (d, s))
        self.pin(x + 20, y - 30, top, 'R'); self.pin(x + 20, y + 30, bot, 'R'); self.pin(x - 20, y, g, 'L'); self.pin(x + 20, y, b, 'R')
    def cap(self, name, x, y, val, top, bot):
        self.out.append(f'C {{capa.sym}} {x} {y} 0 0 {{name={name} m=1 value=\'{val}\' footprint=1206 device="ceramic capacitor"}}')
        self.pin(x, y - 30, top, 'T'); self.pin(x, y + 30, bot, 'B')
    def inst(self, name, symname, x, y, pins, params):
        """pins: ordered list of nets (symbol pin order); drawn as lab_pins on the left (inputs) / right"""
        attr = f'name={name}\n' + '\n'.join(f"{k}='{v}'" for k, v in params.items())
        self.out.append(f'C {{{symname}.sym}} {x} {y} 0 0 {{{attr}}}')
    def ports(self, items, x0=-700, y0=-300):
        for i, (k, lab) in enumerate(items):
            self.out.append(f'C {{{k}.sym}} {x0 if k != "opin" else 700} {y0 + 40 * i} 0 {1 if k == "opin" else 0} {{name={self.nm("io")} lab={lab}}}')
    def text(self, t): self.out.append(f'T {{{t}}} -700 -360 0 0 0.3 0.3 {{}}')
    def write(self, name): open(os.path.join(X, name + '.sch'), 'w').write('\n'.join(self.out) + '\n')
def sym(name, ins, outs, inouts, template='name=x1', fmt='@name @pinlist @symname'):
    s = ['v {xschem version=3.4.7 file_version=1.2}', 'G {}', f'K {{type=subcircuit\nformat="{fmt}"\ntemplate="{template}"\n}}', 'V {}', 'S {}', 'E {}']
    h = 20 * max(len(ins), len(outs), 2) + 20
    s += [f'L 4 -60 {-h} 60 {-h} {{}}', f'L 4 60 {-h} 60 {h} {{}}', f'L 4 60 {h} -60 {h} {{}}', f'L 4 -60 {h} -60 {-h} {{}}']
    for i, lab in enumerate(ins):
        y = -h + 40 + 40 * i
        s += [f'L 4 -80 {y} -60 {y} {{}}', f'B 5 -82.5 {y-2.5} -77.5 {y+2.5} {{name={lab} dir=in}}', f'T {{{lab}}} -55 {y-4} 0 0 0.2 0.2 {{}}']
    for i, lab in enumerate(outs):
        y = -h + 40 + 40 * i
        s += [f'L 4 60 {y} 80 {y} {{}}', f'B 5 77.5 {y-2.5} 82.5 {y+2.5} {{name={lab} dir=out}}', f'T {{{lab}}} 55 {y-4} 0 1 0.2 0.2 {{}}']
    for i, lab in enumerate(inouts):
        xx = -20 + 40 * i
        yy, y0 = (-h - 20, -h) if lab.startswith('vdd') else (h + 20, h)
        s += [f'L 4 {xx} {y0} {xx} {yy} {{}}', f'B 5 {xx-2.5} {yy-2.5} {xx+2.5} {yy+2.5} {{name={lab} dir=inout}}']
    s += [f'T {{{name}}} 0 -8 0 0 0.3 0.3 {{}}', 'T {@name} 62 -100 0 0 0.25 0.25 {}']
    open(os.path.join(X, name + '.sym'), 'w').write('\n'.join(s) + '\n')
# ---------------- cmp_inv: pins i | o | vdd vss, params WN WP
v = Sch()
v.mos('n', 'n', -100, 60, 'WN', '0.28u', 'o', 'i', 'vss', 'vss')
v.mos('p', 'p', -100, -60, 'WP', '0.28u', 'o', 'i', 'vdd', 'vdd')
v.ports([('ipin', 'i'), ('opin', 'o'), ('iopin', 'vdd'), ('iopin', 'vss')], -300, -100)
v.text('cmp_inv: minimum inverter used as clock inverter and output buffers (generated by scripts/gen_cmp_sch.py).')
v.write('cmp_inv'); sym('cmp_inv', ['i'], ['o'], ['vdd', 'vss'], 'name=x1 WN=1u WP=2u', '@name @pinlist @symname WN=@WN WP=@WP')
# ---------------- comparator (cmp_p): pins inp inn clk | outp outn | vdd_cmp vss   (F1 / Decision 44d: the supply pin is vdd_cmp = the ADC-main strap; cmp_inv keeps vdd)
c = Sch()
# stage 1: PMOS tail (gate clkb), PMOS input pair, NMOS reset of the preamp nodes
c.mos('p', 'mt1', -400, -200, 'CMP_WT', 'CMP_LT', 'tl', 'clkb', 'vdd_cmp', 'vdd_cmp')
c.mos('p', 'm1', -520, -80, 'CMP_WP', 'CMP_LP', 'a1', 'inp', 'tl', 'vdd_cmp')
c.mos('p', 'm2', -280, -80, 'CMP_WP', 'CMP_LP', 'a2', 'inn', 'tl', 'vdd_cmp')
c.mos('n', 'mr1', -520, 60, 'CMP_WR', 'CMP_LR', 'a1', 'clkb', 'vss', 'vss')
c.mos('n', 'mr2', -280, 60, 'CMP_WR', 'CMP_LR', 'a2', 'clkb', 'vss', 'vss')
c.cap('cxa1', -620, 60, 'CMP_CA', 'a1', 'vss')
c.cap('cxa2', -180, 60, 'CMP_CA', 'a2', 'vss')
# stage 2: control devices, cross-coupled NMOS, cross-coupled PMOS, precharge PMOS
c.mos('n', 'mc1', -80, 140, 'CMP_WC', 'CMP_LC', 's1', 'a1', 'vss', 'vss')
c.mos('n', 'mc2', 160, 140, 'CMP_WC', 'CMP_LC', 's2', 'a2', 'vss', 'vss')
c.mos('n', 'mn1', -80, 20, 'CMP_WN', 'CMP_LN', 'o1', 'o2', 's1', 'vss')
c.mos('n', 'mn2', 160, 20, 'CMP_WN', 'CMP_LN', 'o2', 'o1', 's2', 'vss')
c.mos('p', 'mq1', -80, -100, 'CMP_WQ', 'CMP_LQ', 'o1', 'o2', 'vdd_cmp', 'vdd_cmp')
c.mos('p', 'mq2', 160, -100, 'CMP_WQ', 'CMP_LQ', 'o2', 'o1', 'vdd_cmp', 'vdd_cmp')
c.mos('p', 'mp1', -80, -220, 'CMP_WS', 'CMP_LS', 'o1', 'clk', 'vdd_cmp', 'vdd_cmp')
c.mos('p', 'mp2', 160, -220, 'CMP_WS', 'CMP_LS', 'o2', 'clk', 'vdd_cmp', 'vdd_cmp')
# clock inverter and output buffers (cmp_inv)
def inv(name, x, y, i, o, wn, wp):
    c.out.append(f"C {{cmp_inv.sym}} {x} {y} 0 0 {{name=X{name}\nWN='{wn}'\nWP='{wp}'}}")
    c.pin(x - 80, y - 20, i, 'L'); c.pin(x + 80, y - 20, o, 'R'); c.pin(x - 20, y - 80, 'vdd_cmp', 'T'); c.pin(x + 20, y + 80, 'vss', 'B')
inv('ic', 340, -240, 'clk', 'clkb', 'CMP_WI', '2*CMP_WI')
inv('b1', 340, -120, 'o1', 'b1', 'CMP_WI', '2*CMP_WI')
inv('b2', 560, -120, 'b1', 'outp', 'CMP_WB', '2*CMP_WB')
inv('b3', 340, 0, 'o2', 'b2', 'CMP_WI', '2*CMP_WI')
inv('b4', 560, 0, 'b2', 'outn', 'CMP_WB', '2*CMP_WB')
c.ports([('ipin', 'inp'), ('ipin', 'inn'), ('ipin', 'clk'), ('opin', 'outp'), ('opin', 'outn'), ('iopin', 'vdd_cmp'), ('iopin', 'vss')])
c.text('D1 dynamic comparator (PMOS-input double-tail, cell cmp_p; generated by scripts/gen_cmp_sch.py).  Sizes = spice/comparator_params.spice.  The trnoise injection sources of the hand netlist are simulation-only and not drawn.')
c.write('cmp_p'); sym('cmp_p', ['inp', 'inn', 'clk'], ['outp', 'outn'], ['vdd_cmp', 'vss'])
print('wrote xschem/cmp_p.{sch,sym}, cmp_inv.{sch,sym}')
