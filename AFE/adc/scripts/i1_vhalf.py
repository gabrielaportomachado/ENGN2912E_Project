#!/usr/bin/env python3
"""I1: transistor-level check of the per-ADC VDD/2 divider (spice/vhalf.spice).  Two frames at the D5 timing (scripts/d5lib.controls): frame 1 converts vin1 and resumes tracking, frame 2 samples vin2 (1 V step, the worst
sample-to-sample change), then 12 comparator evaluations (6 ns pulses, 500 ns apart, first 130 ns after CS falling, bottoms held at the frame-2 pattern -> plate near balance = worst comparator kickback).
Reference v_ref = v(vcmd) just BEFORE the plate reset switch opens in frame 2 (the value the plate samples).  (a) e_a = v(vcmd) - v_ref just before each decision (sample kick + any unsettled recovery of the frame-1 resume kick);
(b) e_b = max |v(vcmd) - v_ref| in the 3 ns after each comparator rise (kickback); (c) static current; also the peak excursion after the frame-1 resume (TG closing with the bottoms at the old code).
usage: python3 i1_vhalf.py <C_pF> [R_ohm_each] ; env CORNERS='typical:27,ss:125,ff:-40'; log lines to stdout.  Runs the corners in parallel, kills by PID after TMO seconds (default 900)."""
import os, sys, subprocess, time, tempfile, shutil, numpy as np
H = os.path.dirname(os.path.abspath(__file__)); ADC = os.path.abspath(os.path.join(H, '..')); sys.path.insert(0, H)
import d5lib as D
C_PF = float(sys.argv[1]); R = float(sys.argv[2]) if len(sys.argv) > 2 else 250e3
VR_PF = float(os.environ.get('VR', 0))   # I2: Cref (pF) behind the sampling switch on cmp_p.inp; 0 = I1 netlist (inp = vcmd)
VIN1 = float(os.environ.get('VIN1', 1.15)); VIN2 = float(os.environ.get('VIN2', 2.15))
TS1 = 100e-6; TS2 = TS1 + D.TFRAME; TEND = TS2 + 8e-6
TB = """* I1 vhalf check (generated by scripts/i1_vhalf.py)
.include ../../amp/spice/models_@CORNER@.spice
.include ../spice/dac_units.spice
.include ../spice/dac_sw.spice
.include ../spice/comparator_params.spice
.include ../spice/comparator.spice
.include ../spice/vhalf.spice
.param VH_C=@C@p VH_R=@R@ VR_C=@VR@p
.options gmin=1e-14 abstol=1e-15 reltol=1e-4 vntol=1e-7 itl1=500 itl4=500 chgtol=1e-17 num_threads=1
.temp @TEMP@
.param VSUP=3.3
Vdd vdd 0 {VSUP}
Vin vin 0 PWL(0 @V1@ @TV@ @V1@ @TV1@ @V2@)
@CTRL@
Vck ck 0 PWL(@CK@)
Xvh vcmd vdd 0 vhalf
Xs vin t m vcmd vdd vdd 0 rst rstm sam samb gp0 gp1 gp2 gp3 gp4 gp5 gp6 gp7 gp8 gp9 gp10 gp11 gdp gn0 gn1 gn2 gn3 gn4 gn5 gn6 gn7 gn8 gn9 gn10 gn11 gdn dac_sw
@XR@
Xc @CI@ t ck outp outn vdd 0 cmp_p
Cl1 outp 0 5f
Cl2 outn 0 5f
.nodeset v(vcmd)=1.65 v(t)=1.65 v(m)=1.65
.tran 2n @TEND@ 0 @TMAX@
.control
set wr_singlescale
set wr_vecnames
run
wrdata @OUT@ v(vcmd) v(t) i(Vdd) v(ci)
quit
.endc
.end
"""
def one(corner, temp, tmpd):
    code1 = int(VIN1 / D.LSB); code2 = int(VIN2 / D.LSB)
    ctrl, _ = D.controls([(TS1, code1), (TS2, code2)])
    ck = [(0.0, 0.0)]; tcks = []
    for k in range(12):
        t0 = TS2 + 130e-9 + k * 500e-9; tcks.append(t0); ck += [(t0, 0.0), (t0 + 0.2e-9, 3.3), (t0 + 6e-9, 3.3), (t0 + 6.2e-9, 0.0)]
    ckt = ' '.join(f'{a:.10e} {b}' for a, b in ck)
    tbn = f'{tmpd}/tb_{corner}_{temp}.spice'; out = f'{tmpd}/o_{corner}_{temp}.csv'
    t = TB
    for k, v in dict(CORNER=corner, TEMP=temp, C=f'{C_PF:g}', R=f'{R:g}', V1=VIN1, V2=VIN2, TV=TS1 + 3e-6, TV1=TS1 + 3.1e-6, CTRL=ctrl.replace('\n', '\n'), CK=ckt, VR=f'{VR_PF:g}', XR=('Xr vcmd ci sam samb vdd 0 vrefs' if VR_PF > 0 else 'Vc0 ci vcmd 0'), CI='ci', TEND=TEND, TMAX=float(os.environ.get('TMAXS', 4e-9)), OUT=out).items(): t = t.replace(f'@{k}@', str(v))
    open(tbn, 'w').write(t)
    p = subprocess.Popen(['ngspice', '-b', tbn], cwd=f'{ADC}/tb', stdout=open(f'{tmpd}/log_{corner}_{temp}.txt', 'w'), stderr=subprocess.STDOUT)
    return p, out, tcks
if __name__ == '__main__':
    corners = [tuple(c.split(':')) for c in os.environ.get('CORNERS', 'typical:27,ss:125,ff:-40').split(',')]
    os.makedirs(f'{ADC}/sim/.ptmp', exist_ok=True); tmpd = tempfile.mkdtemp(prefix='i1_', dir=f'{ADC}/sim/.ptmp')
    # the tb uses relative includes: run from tb/, so write the tb into tmpd but cwd = tb/ (includes resolve against cwd)
    procs = [(c, one(c[0], c[1], tmpd)) for c in corners]; t0 = time.time(); TMO = float(os.environ.get('TMO', 900))
    for c, (p, out, tcks) in procs:
        while p.poll() is None and time.time() - t0 < TMO: time.sleep(2)
        if p.poll() is None: p.kill(); p.wait(); print(f'{c} KILLED after {TMO}s'); continue
        if not os.path.exists(out): print(c, 'NO OUTPUT', open(f'{tmpd}/log_{c[0]}_{c[1]}.txt').read()[-300:]); continue
        shutil.copy(out, f'{ADC}/sim/.ptmp/i1_raw_C{C_PF:g}_{c[0]}_{c[1]}.csv'); a = np.loadtxt(out, skiprows=1); t, v, vt, idd = a[:, 0], a[:, 1], a[:, 2], a[:, 3]; vci = a[:, 4]
        vi = lambda tt: np.interp(tt, t, vci)       # reference node seen by the comparator (= vcmd when VR = 0)
        vref = vi(TS2 - 0.2e-9); settle = (np.interp(TS2 - 0.2e-9, t, vci) - np.interp(TS2 - 0.2e-9, t, v)) * 1e6; vh_err = (np.interp(TS2 - 0.2e-9, t, v) - 1.65) * 1e6
        ea = max(abs(vi(tc - 0.3e-9) - vref) for tc in tcks)
        eb = max(np.max(np.abs(v[(t >= tc) & (t <= tc + 3e-9)] - vref)) for tc in tcks)
        w = (t > TS1 + 9e-6) & (t < TS1 + 40e-6); pk = np.max(np.abs(v[w] - vref))
        w2 = (t > TS1 - 1e-6) & (t < TS1); static = vi(TS2 - 1e-6)
        print(f'C {C_PF:g} pF R {R/1e3:.0f}k {c[0]} {c[1]}C: vhalf(static) {static:.5f} V (VDD/2 = 1.65)  resume-kick peak {pk*1e3:.2f} mV  v_ref-static {(vref-static)*1e6:.1f} uV  '
              f'(a) |v(decision)-v_ref| max {ea*1e6:.1f} uV = {ea/D.LSB:.3f} LSB   (b) kickback max {eb*1e6:.1f} uV = {eb/D.LSB:.3f} LSB   (c) Idd(static) {-np.interp(TS2-1e-6,t,idd)*1e6:.2f} uA  Cref {VR_PF:g} pF: ref-node minus vhalf before the sample {settle:+.1f} uV, vhalf - 1.65 V {vh_err:+.1f} uV')
    shutil.rmtree(tmpd, ignore_errors=True)
