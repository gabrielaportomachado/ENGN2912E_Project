#!/usr/bin/env python3
"""Write a DAC netlist (subckt dac_units t m b0..b11 bd) from a d2lib.Dac: every unit is a PDK MIM instance (cap_mim_2f0_m2m3_noshield, c_length 5u, c_width solved for the wanted C)
usage as module: write_dac(path, dac, corner);  CLI: gen_dac.py <out.spice> [seed A_C]  (no seed = nominal)"""
import sys, os, numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__))); from d2lib import *
def write_dac(path, d, corner='typical', title='D2 split-cap DAC'):
    nb = d.l + d.m; ports = ' '.join(['t', 'm'] + [f'b{j}' for j in range(nb)] + ['bd'])
    s = [f'* {title}: 6+6 split, units 5 x 5 um MIM (PDK cap_mim_2f0), bridge T-M, dummy unit on M (bottom pin bd).  Generated by scripts/gen_dac.py; widths solved so that C = nominal*(1+dev).', f'.subckt dac_units {ports}']
    for j, ul in enumerate(d.bit_units):
        top = 't' if j >= d.l else 'm'
        for u in ul: s.append(f'Xc{j}_{u} {top} b{j} cap_mim_2f0_m2m3_noshield c_length=5u c_width={width_for(d.units[u], 5e-6, corner)*1e6:.6f}u')
    s.append(f'Xcd m bd cap_mim_2f0_m2m3_noshield c_length=5u c_width={width_for(d.units[d.dummy[0]], 5e-6, corner)*1e6:.6f}u')
    s.append(f'Xcb t m cap_mim_2f0_m2m3_noshield c_length=5u c_width={width_for(d.cb, 5e-6, corner)*1e6:.6f}u')
    s.append('.ends dac_units'); open(path, 'w').write('\n'.join(s) + '\n')
if __name__ == '__main__':
    out = sys.argv[1]
    if len(sys.argv) > 2: d = Dac(sig=float(sys.argv[3]) / 100 / 5.0, rng=np.random.default_rng(int(sys.argv[2])))
    else: d = Dac()
    write_dac(out, d)
