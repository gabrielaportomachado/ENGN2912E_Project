#!/usr/bin/env python3
"""I2: D4b-style replay with the TRUE binary 12-trial SAR sequence (ideal decisions as scripted PWL controls, scripts/d2_conv.control) into transistor-level dac_sw + cmp_p, with the VDD/2 reference in four variants:
  ideal  : ideal 1.65 V source on dac_sw.vcm and cmp_p.inp (the reference run)
  vhalf  : I1 divider (2 x 250k, C = VH_C) on both (option iv)
  cref   : vhalf (C = VH_C) on dac_sw.vcm; cmp_p.inp = Cref (VR_C) behind a TG closed while sam = 1 (opens with the sampling TG, 3 ns after the plate switch)
  crefr  : same, but the TG is gated by rst (opens WITH the plate reset switch, 1 ns after rstm; needs a complement, ideal here)
Comparator clock = D4b STA instants (dtc after the DAC edge, width W) per corner.  Metric per trial k: d_k = (V_plate - V_inp) at the clock rise + 1.5 ns [LSB]; code error = d_k(variant) - d_k(ideal) (late trials 9-12 set the code).
usage: i2_replay.py <variant:VH_pF:VR_pF,...> <corner:tempC,...> <vin,vin,...>   -> one line per (variant, corner, vin); jobs are pinned one per core (taskset), up to 8 at a time, killed by PID after TMO s (default 900)"""
import sys, os, subprocess, tempfile, shutil, time, numpy as np
H = os.path.dirname(os.path.abspath(__file__)); ADC = os.path.abspath(os.path.join(H, '..')); sys.path.insert(0, H)
import d2_conv as dc; from d2lib import *
VDD = 3.3; LSB = VDD / 4096; T = 500e-9
STA = {'ff': (21.0e-9, 3.2e-9), 'typical': (39.6e-9, 5.9e-9), 'ss': (83.8e-9, 12.3e-9)}
TB = """* I2 replay (generated by scripts/i2_replay.py), variant @VAR@
.include ../../amp/spice/models_@CORNER@.spice
.include ../spice/dac_units.spice
.include ../spice/dac_sw.spice
.include ../spice/comparator_params.spice
.include ../spice/comparator.spice
.include ../spice/vhalf.spice
.param VH_C=@VHC@p VR_C=@VRC@p
.options gmin=1e-12 reltol=1e-4 abstol=1e-15 vntol=1e-7 chgtol=1e-17 itl1=500 itl4=500 num_threads=1
.temp @TEMP@
.param VSUP=3.3
Vdd vdd 0 {VSUP}
@REF@
.include @CTRL@
Vck ck 0 PWL(@CK@)
Xs vin t m vcmd vdd 0 rst rstm sam samb gp0 gp1 gp2 gp3 gp4 gp5 gp6 gp7 gp8 gp9 gp10 gp11 gdp gn0 gn1 gn2 gn3 gn4 gn5 gn6 gn7 gn8 gn9 gn10 gn11 gdn dac_sw
@CI@
Xc ci t ck outp outn vdd 0 cmp_p
Cl1 outp 0 5f
Cl2 outn 0 5f
.tran 20p @TEND@ 0 50p
.control
set wr_singlescale
save v(t) v(ci) v(vcmd) v(outp)
run
wrdata @OUT@ v(t) v(ci) v(vcmd) v(outp)
quit
.endc
.end
"""
REF = {'ideal': 'Vh vcmd 0 1.65', 'vhalf': 'Xvh vcmd vdd 0 vhalf', 'cref': 'Xvh vcmd vdd 0 vhalf', 'crefr': 'Xvh vcmd vdd 0 vhalf'}
CI = {'ideal': 'Vc0 ci vcmd 0', 'vhalf': 'Vc0 ci vcmd 0', 'cref': 'Xr vcmd ci sam samb vdd 0 vrefs',
      'crefr': 'Erb rstb 0 vol=\'3.3-V(rst)\'\nXr vcmd ci rst rstb vdd 0 vrefs'}
def ideal_seq(vin, d):
    lv = d.levels(); code = 0; seq = []; tri = []
    for j in range(11, -1, -1):
        tr = code | (1 << j); tri.append(tr); k = vin >= lv[tr]; seq.append(int(k))
        if k: code = tr
    return code, seq, tri
def start(var, corner, temp, vhc, vrc, vin, tmpd):
    d = Dac(); code, seq, tri = ideal_seq(vin, d)
    ctrl, tend, info = dc.control('conv', [vin], T, d=d); ts, to, tc0, te = info[0]
    dtc, W = STA[corner]; pts = [(0.0, 0.0)]
    for k in range(12):
        tk = tc0 + k * T + dtc; pts += [(tk, 0.0), (tk + 0.2e-9, VDD), (tk + W, VDD), (tk + W + 0.2e-9, 0.0)]
    tag = f'{var}_{corner}_{temp}_{vin:.5f}'; open(f'{tmpd}/c_{tag}.inc', 'w').write(ctrl); out = f'{tmpd}/o_{tag}.csv'
    t = TB
    for k, v in dict(VAR=var, CORNER=corner, VHC=f'{vhc:g}', VRC=f'{vrc:g}', TEMP=temp, REF=REF[var], CI=CI[var], CTRL=f'{tmpd}/c_{tag}.inc', CK=' '.join(f'{a:.6e} {b}' for a, b in pts), TEND=f'{tend:.6e}', OUT=out).items(): t = t.replace(f'@{k}@', v)
    open(f'{tmpd}/tb_{tag}.spice', 'w').write(t)
    return ['taskset', '-c', '{core}', 'ngspice', '-b', f'{tmpd}/tb_{tag}.spice'], f'{tmpd}/l_{tag}.txt', out, (code, seq, tc0, ts, to, tri), tag
def analyse(out, meta):
    code, seq, tc0, ts, to = meta; dtc, W = None, None
    a = np.loadtxt(out, skiprows=1); t, vt, vci, vh, op = a[:, 0], a[:, 1], a[:, 3], a[:, 5], a[:, 7]
    return t, vt, vci, vh, op
def report(var, corner, temp, vhc, vrc, vin, out, meta, tmpd, tag):
    code, seq, tc0, ts, to, tri = meta; dtc, W = STA[corner]
    a = np.loadtxt(out, skiprows=1); t = a[:, 0]
    np.save(f'{ADC}/sim/.ptmp/i2raw_{var}_{corner}_{temp}_{vhc:g}_{vrc:g}_{vin:.5f}.npy', a)
    vt, vci, vh = a[:, 1], a[:, 2], a[:, 3]; op = a[:, 4]; rows = []
    for k in range(12):
        tc = tc0 + k * T + dtc
        d_ev = (np.interp(tc + 1.5e-9, t, vt) - np.interp(tc + 1.5e-9, t, vci)) / LSB
        e_ref = (np.interp(tc - 0.1e-9, t, vci) - np.interp(to - 0.1e-9, t, vci)) / LSB     # ref-node change since just before the plate switch opens
        e_ev = (np.interp(tc + 1.5e-9, t, vci) - np.interp(to - 0.1e-9, t, vci)) / LSB
        rows.append((d_ev, e_ref, e_ev, int(np.interp(tc + W - 0.2e-9, t, op) > VDD / 2)))
    dsamp = (np.interp(to + 20e-9, t, vci) - np.interp(to - 0.1e-9, t, vci)) / LSB
    vsamp = (np.interp(to - 0.1e-9, t, vci) - 1.65) / LSB
    print(f'I2 {var} {corner} {temp}C VH {vhc:g} VR {vrc:g} vin {vin:.5f} code {code} | d_ev[LSB] ' + ' '.join(f'{r[0]:+.2f}' for r in rows) + ' | e_ref_pre[LSB] ' + ' '.join(f'{r[1]:+.2f}' for r in rows) + ' | e_ref_ev ' + ' '.join(f'{r[2]:+.2f}' for r in rows) +
          f' | dec ' + ''.join(str(r[3]) for r in rows) + ' ideal ' + ''.join(map(str, seq)) + ' tri ' + ','.join(map(str, tri)) + f' | ref(open)-1.65V {vsamp:+.3f} LSB, step in 20 ns {dsamp:+.3f} LSB', flush=True)
if __name__ == '__main__':
    vspec = [x.split(':') for x in sys.argv[1].split(',')]; cspec = [x.split(':') for x in sys.argv[2].split(',')]; vins = [float(x) for x in sys.argv[3].split(',')]
    os.makedirs(f'{ADC}/sim/.ptmp', exist_ok=True); tmpd = tempfile.mkdtemp(prefix='i2_', dir=f'{ADC}/sim/.ptmp')
    todo = [(v[0], float(v[1]), float(v[2]), c[0], c[1], vin) for v in vspec for c in cspec for vin in vins]
    TMO = float(os.environ.get('TMO', 900)); free = list(range(int(os.environ.get('NCORE', 8)))); run = []
    while todo or run:
        while todo and free:
            var, vhc, vrc, corner, temp, vin = todo.pop(0); cmd, lg, out, meta, tag = start(var, corner, temp, vhc, vrc, vin, tmpd); core = free.pop(0)
            cmd = [x.replace('{core}', str(core)) for x in cmd]; p = subprocess.Popen(cmd, cwd=f'{ADC}/tb', stdout=open(lg, 'w'), stderr=subprocess.STDOUT)
            run.append((p, core, time.time(), (var, corner, temp, vhc, vrc, vin, out, meta, tmpd, tag), lg))
        time.sleep(0.5)
        for r in list(run):
            p, core, t0, args, lg = r
            if p.poll() is None and time.time() - t0 > TMO: p.kill(); p.wait(); print(f'KILLED {args[:6]}', flush=True)
            if p.poll() is not None:
                run.remove(r); free.append(core)
                if os.path.exists(args[6]) and os.path.getsize(args[6]) > 1000: report(*args)
                else: print('NO OUTPUT', args[:6], open(lg).read()[-150:].replace('\n', ' '), flush=True)
    shutil.rmtree(tmpd, ignore_errors=True)
