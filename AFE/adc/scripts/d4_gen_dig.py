#!/usr/bin/env python3
"""D4: convert the synthesized D3 netlist (lg/runs/d3/final/nl/adc8_top.nl.v) into an XSPICE gate-level include file with per-instance delays from an SDF (OpenSTA, nom SPEF, one lib corner).
Each std cell becomes one A-device: combinational cell = d_lut (truth table from the liberty 'function'), D flip-flop = d_dff (async reset via an inverted RN net), negedge flop = d_dff behind a d_inverter on the clock.
Delay of a cell output = max over its IOPATH arcs, rise and fall separately (SDF); INTERCONNECT delays (max 0.12 ns) are ignored.  Fill / tap / endcap cells are skipped.
usage: d4_gen_dig.py <lib corner> <out.inc>      Digital node names: d_<port><bit> for ports, n_<net> for internal nets."""
import re, sys, os
ADC = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
corner, out = sys.argv[1], sys.argv[2]
LIB = f'/foss/pdks/gf180mcuD/libs.ref/gf180mcu_fd_sc_mcu7t5v0/lib/gf180mcu_fd_sc_mcu7t5v0__{corner}.lib'
nl = open(f'{ADC}/lg/runs/d3/final/nl/adc8_top.nl.v').read()
sdf = open(f'{ADC}/spice/dig/adc8_{corner}.sdf').read()
lib = open(LIB).read()
def cellfunc(t):
    i = lib.index(f'cell(gf180mcu_fd_sc_mcu7t5v0__{t})'); j = lib.find('\n  cell(', i + 10); blk = lib[i:j if j > 0 else None]
    outs = {}; cur = None
    for ln in blk.splitlines():
        m = re.match(r'\s*pin\((\w+)\)', ln)
        if m: cur = m.group(1)
        f = re.match(r'\s*function\s*:\s*"([^"]*)"', ln)
        if f and cur: outs[cur] = f.group(1)
    return outs
# ---- parse the netlist
body = nl[nl.index(');') + 2:]
insts = []
for m in re.finditer(r'\n\s*(gf180mcu_fd_sc_mcu7t5v0__(\w+))\s+(\S+)\s*\((.*?)\);', body, re.S):
    full, typ, name, pins = m.groups()
    if re.match(r'(fill|filltie|endcap|decap)', typ): continue
    conn = dict((p, n.strip()) for p, n in re.findall(r'\.(\w+)\(([^)]*)\)', pins))
    insts.append((typ, name.replace('\\', ''), conn))
assigns = re.findall(r'\n\s*assign\s+(\S+)\s*=\s*(\S+);', body)
def nname(n):
    n = n.strip().replace('\\', '').strip()
    if n in ("1'h0", "1'b0"): return 'zero_d'
    if n in ("1'h1", "1'b1"): return 'one_d'
    m = re.match(r'^(\w+)\[(\d+)\]$', n)
    ports = {'cs_n', 'sclk', 'din', 'rstn', 'cmp_q', 'cmp_clk', 'dac_gp', 'dac_gn', 'rst_sw', 'tg_on', 'dout', 'dout_oe', 'mode_o', 'en_o'}
    if m and m.group(1) in ports: return f'd_{m.group(1)}{m.group(2)}'
    if n in ports: return f'd_{n}'
    return 'n_' + re.sub(r'\W', '_', n)
# ---- SDF delays per instance
dly = {}
for m in re.finditer(r'\(CELL\s*\(CELLTYPE "[^"]*"\)\s*\(INSTANCE (\S+)\)(.*?)\n \)\n', sdf, re.S):
    inst, blk = m.groups(); inst = inst.replace('\\', ''); arcs = {}
    for a in re.finditer(r'\(IOPATH (?:\((?:posedge|negedge) )?(\w+)\)? (\w+) \(([-\d.]*)::?([-\d.]*)\)\s*(?:\(([-\d.]*)::?([-\d.]*)\))?', blk):
        pin, o, r1, r2, f1, f2 = a.groups()
        def v(x1, x2):
            x = x2 or x1
            return float(x) if x else None
        arcs.setdefault((pin, o), []).append((v(r1, r2), v(f1, f2)))
    dly[inst] = arcs
def delays(inst, outpin='Z', pins=None):
    arcs = dly.get(inst, {}); rs, fs = [], []
    for (p, o), L in arcs.items():
        if o != outpin or (pins and p not in pins): continue
        for r, f in L:
            if r is not None: rs.append(r)
            if f is not None: fs.append(f)
    if not rs and not fs: print('WARNING no SDF arcs for', inst, outpin)
    r = max(rs) if rs else 0.1; f = max(fs) if fs else 0.1
    return max(r, 0.002), max(f, 0.002)
def eval_tt(func, pins):
    f = func.replace('!', ' not ').replace('*', ' and ').replace('+', ' or ').replace('&', ' and ').replace('|', ' or ').replace('^', ' != ')
    tt = []
    for idx in range(2 ** len(pins)):
        env = {p: bool((idx >> k) & 1) for k, p in enumerate(pins)}   # first listed input = LSB (checked in ngspice)
        env2 = dict(env); tt.append('1' if eval(f, {}, env2) else '0')
    return ''.join(tt)
L = [f'* D4 XSPICE gate-level model of adc8_top (synthesized D3 netlist), delays from {os.path.basename(corner)} SDF (OpenSTA, nom SPEF).  Generated by scripts/d4_gen_dig.py - do not edit.']
mod = []; k = 0; rnets = {}; nflop = ncomb = 0
INV_DELAY = '1p'
for typ, name, c in insts:
    k += 1; nm = re.sub(r'\W', '_', name)
    if typ.startswith('dff'):
        d, clk, q = nname(c['D']), nname(c.get('CLK') or c['CLKN']), nname(c['Q'])
        rn = nname(c['RN']) if 'RN' in c else None
        cd = delays(name, 'Q', ['CLK', 'CLKN'])
        cdl = max(cd)
        if rn:
            if rn not in rnets:
                rnets[rn] = f'{rn}_inv'; L.append(f'Ainv_{rnets[rn]} {rn} {rnets[rn]} mi_rst'); 
            rst = rnets[rn]
        else: rst = 'zero_d'
        if typ.startswith('dffn'):
            cinv = f'{nm}_clkb'; L.append(f'Aci_{nm} {clk} {cinv} mi_clk'); clk = cinv
        L.append(f'Af_{nm} {d} {clk} zero_d {rst} {q} nq_{nm} mf_{nm}')
        mod.append(f'.model mf_{nm} d_dff(clk_delay={cdl*1e-9:.4e} reset_delay=20p set_delay=20p ic=0)')
        nflop += 1
    else:
        fo = cellfunc(typ)
        for op, f in fo.items():
            ins = [p for p in c if p != op and p in re.findall(r'[A-Z][A-Z0-9]*', f)]
            ins = sorted(ins, key=lambda p: (p[0], p))
            ins = [p for p in re.findall(r'[A-Z][A-Z0-9]*', f) if p in c and not (p in ins[:0])]
            seen = []; [seen.append(p) for p in ins if p not in seen]; ins = seen
            tt = eval_tt(f, ins)
            r, fl = delays(name, op)
            nodes = ' '.join(nname(c[p]) for p in ins); o = nname(c[op])
            if len(ins) == 1:
                L.append(f'Ag_{nm} [{nodes}] {o} ml_{nm}')
            else:
                L.append(f'Ag_{nm} [{nodes}] {o} ml_{nm}')
            mod.append(f'.model ml_{nm} d_lut(table_values "{tt}" rise_delay={r*1e-9:.4e} fall_delay={fl*1e-9:.4e})')
            ncomb += 1
L.append('.model mi_rst d_inverter(inertial_delay=false rise_delay=1p fall_delay=1p)')
L.append('.model mi_clk d_inverter(inertial_delay=false rise_delay=1p fall_delay=1p)')
L += mod
open(out, 'w').write('\n'.join(L) + '\n')
print(f'{corner}: {nflop} flops, {ncomb} combinational cells, {len(rnets)} reset inverters -> {out}')
