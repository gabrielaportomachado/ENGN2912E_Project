#!/usr/bin/env python3
"""Writes a TESTBENCH-ONLY copy of cmp_p with thermal-noise sources (the cell spice/comparator.spice and the schematic stay noise-free).
usage: mk_noisy_cell.py <out.spice> <NA_pair> <NV_c> <NV_n> <NT>
  Ixn1/2: current noise across the input pair (drain-tail), one-sided PSD 2*NA^2*NT = 4kT*gamma*gm
  Inc/Rnc, Inn/Rnn: gate-referred voltage noise v = i_n*1k (a trnoise current into a 1 kOhm series resistor; a series trnoise VOLTAGE source aborted .tran) on the gates of the control devices Mc1/Mc2 and of the latch NMOS Mn1/Mn2; one-sided PSD 2*NV^2*NT = 4kT*gamma/gm
  (series gate noise is automatically gated by the device: it only acts while the device conducts)."""
import re, sys, os
out, na, nvc, nvn, nt = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4], sys.argv[5]
src = open(os.path.join(os.path.dirname(__file__), '..', 'spice', 'comparator.spice')).read()
blk = re.search(r'\.subckt cmp_p .*?\.ends cmp_p', src, re.S).group(0).replace('cmp_p', 'cmp_p_nz')
blk = blk.replace('Xmc1 s1 a1 ', 'Xmc1 s1 gc1 ').replace('Xmc2 s2 a2 ', 'Xmc2 s2 gc2 ').replace('Xmn1 o1 o2 s1 ', 'Xmn1 o1 gn1 s1 ').replace('Xmn2 o2 o1 s2 ', 'Xmn2 o2 gn2 s2 ')
add = (f"Ixn1 a1 tl dc 0 trnoise({na} {nt} 0 0)\nIxn2 a2 tl dc 0 trnoise({na} {nt} 0 0)\n"
       f"Rnc1 gc1 a1 1k\nRnc2 gc2 a2 1k\nRnn1 gn1 o2 1k\nRnn2 gn2 o1 1k\n"
       f"Vnc1 0 0 0\n" if False else
       f"Rnc1 gc1 a1 1k noisy=0\nRnc2 gc2 a2 1k noisy=0\nRnn1 gn1 o2 1k noisy=0\nRnn2 gn2 o1 1k noisy=0\n"
       f"Inc1 a1 gc1 dc 0 trnoise({float(nvc)/1000:.6g} {nt} 0 0)\nInc2 a2 gc2 dc 0 trnoise({float(nvc)/1000:.6g} {nt} 0 0)\n"
       f"Inn1 o2 gn1 dc 0 trnoise({float(nvn)/1000:.6g} {nt} 0 0)\nInn2 o1 gn2 dc 0 trnoise({float(nvn)/1000:.6g} {nt} 0 0)\n")
mask = os.environ.get('NZ_MASK', 'pcn')   # p = pair, c = control gates, n = latch gates
add = ''.join(l + '\n' for l in add.splitlines() if (l.startswith('Ixn') and 'p' in mask) or (l.startswith(('Rnc', 'Inc')) and 'c' in mask) or (l.startswith(('Rnn', 'Inn')) and 'n' in mask))
blk = blk.replace('.ends cmp_p_nz', add + '.ends cmp_p_nz')
open(out, 'w').write('* TESTBENCH-ONLY noisy copy of cmp_p (generated by scripts/mk_noisy_cell.py)\n' + blk + '\n')
