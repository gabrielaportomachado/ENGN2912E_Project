#!/usr/bin/env python3
"""ngspice testbench for ONE amplifier channel: bias_genc + amp_ch (from the LVS reference netlists), no digital, no ADC.

    python3 xschem/gen_amp_tb.py --lvs-dir ../AFE/layout/lvs --pdk-root $PDK_ROOT --out build_amp
    cd build_amp && ngspice -b tb_amp.spice
    python3 ../xschem/analyze_amp.py amp_out.txt amp_info.json

Wiring = the one in dbs_afe_top.spice: Xu_bias vbn vcm vg1 vcmo vg2 vrs VDD VSS bias_genc;  amp_ch rec ref sw_rec sw_rec_b rst_amp vbn vcm vg1 vcmo vg2 vrs out vdd vss.
The port lists are read from the netlists and checked against these; the script stops if they differ.

Stimulus: VDD ramps in 2 us; RST_AMP = 1 and the routing switch open (sw_rec = 0, sw_rec_b = VDD) until t_rec (1 ms), then RST_AMP = 0 and sw_rec = VDD (record).
REC = REF + a sine (default 0.45 mV pk, 200 Hz, so 60 dB gives 0.45 V pk); REF = 1.65 V.  The amplifier needs the fast-settle pulse after record starts; the analysis only uses t > --t-meas.
"""
import argparse
import json
import os
import re
import sys

AMP_PORTS = "rec ref sw_rec sw_rec_b rst_amp vbn vcm vg1 vcmo vg2 vrs out vdd vss".split()
BIAS_PORTS = "vbn vcm_in vg1 vcm_out vg2 vrs vdd vss".split()
BIAS_NETS = "vbn vcm vg1 vcmo vg2 vrs vdd vss".split()
SECTIONS = ["typical", "res_typical", "mimcap_typical", "moscap_typical", "diode_typical"]


def subckt_ports(path, name):
    text = re.sub(r"\n\s*\+", " ", open(path).read())
    for line in text.splitlines():
        t = line.split()
        if len(t) >= 2 and t[0].lower() == ".subckt" and t[1].lower() == name:
            return [p.lower() for p in t[2:] if "=" not in p]
    sys.exit(f"no .subckt {name} in {path}")


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--lvs-dir", required=True, help="folder with afe_chc.spice and bias_genc.spice")
    ap.add_argument("--out", default="build_amp")
    ap.add_argument("--pdk-root", default=os.environ.get("PDK_ROOT", "$PDK_ROOT"))
    ap.add_argument("--tone-hz", type=float, default=200.0)
    ap.add_argument("--tone-amp", type=float, default=0.45e-3, help="V peak")
    ap.add_argument("--tstop", type=float, default=30e-3)
    ap.add_argument("--t-rec", type=float, default=1e-3, help="record starts / RST_AMP released")
    ap.add_argument("--cload", type=float, default=2e-12)
    a = ap.parse_args(argv)
    chc = os.path.abspath(os.path.join(a.lvs_dir, "afe_chc.spice"))
    bias = os.path.abspath(os.path.join(a.lvs_dir, "bias_genc.spice"))
    for p, name, exp in ((chc, "amp_ch", AMP_PORTS), (bias, "bias_genc", BIAS_PORTS)):
        got = subckt_ports(p, name)
        if got != exp:
            sys.exit(f"{name} ports in {p} are\n  {got}\nbut this script expects\n  {exp}\nedit AMP_PORTS / BIAS_PORTS after checking how dbs_afe_top.spice wires it")
    os.makedirs(a.out, exist_ok=True)
    tr = a.t_rec
    deck = [
        "* one amplifier channel: bias_genc + amp_ch (generated by gen_amp_tb.py)",
        *[f".lib {a.pdk_root}/gf180mcuD/libs.tech/ngspice/sm141064.ngspice {s}" for s in SECTIONS],
        f".include {a.pdk_root}/gf180mcuD/libs.tech/ngspice/design.ngspice",
        f".include {chc}",
        f".include {bias}",
        "Vdd vdd 0 pwl(0 0 2u 3.3)",
        "Vref ref 0 1.65",
        f"Vrec rec 0 sin(1.65 {a.tone_amp:g} {a.tone_hz:g} 0 0)",
        f"Vrst rst_amp 0 pwl(0 0 2u 3.3 {tr:.10g} 3.3 {tr + 1e-9:.10g} 0)",
        f"Vswr sw_rec 0 pwl(0 0 {tr:.10g} 0 {tr + 1e-9:.10g} 3.3)",
        f"Vswrb sw_rec_b 0 pwl(0 0 2u 3.3 {tr:.10g} 3.3 {tr + 1e-9:.10g} 0)",
        f"Xu_bias {' '.join(BIAS_NETS[:6])} vdd 0 bias_genc",
        f"Xamp {' '.join(p if p != 'vss' else '0' for p in AMP_PORTS)} amp_ch",
        f"Cload out 0 {a.cload:g}",
        ".options abstol=1e-12 reltol=1e-3 method=gear",
        ".temp 27",
        ".save v(out) v(rec) v(vcmo) v(vbn) v(vcm)",
        f".tran 10u {a.tstop:g} 0 20u",
        ".control",
        "set num_threads=1",
        "set wr_singlescale",
        "set wr_vecnames",
        "run",
        "wrdata amp_out.txt v(out) v(rec) v(vcmo)",
        ".endc",
        ".end",
    ]
    open(os.path.join(a.out, "tb_amp.spice"), "w").write("\n".join(deck) + "\n")
    json.dump(dict(tone_hz=a.tone_hz, tone_amp=a.tone_amp, t_rec=a.t_rec, tstop=a.tstop), open(os.path.join(a.out, "amp_info.json"), "w"))
    print(f"wrote {a.out}/tb_amp.spice, amp_info.json")


if __name__ == "__main__":
    main()